package netscape

import (
	"bufio"
	"context"
	"fmt"
	"html"
	"io"
	"sort"
	"strconv"
	"strings"

	"github.com/lisieckir/lynk/internal/bookmark"
)

// Export writes ownerID's bookmarks as one deterministic Netscape HTML document.
// No username, token, password hash or database path is ever included. The
// output contains only the owner's stored URL, title, description, dates, tags
// and the documented reserved state tags.
func Export(ctx context.Context, svc *bookmark.Service, ownerID int64, w io.Writer, opts ExportOptions) error {
	if svc == nil || w == nil {
		return fmt.Errorf("%w: nil bookmark service or writer", ErrInvalidOptions)
	}
	if ownerID <= 0 {
		return fmt.Errorf("%w: owner id must be positive", ErrInvalidOptions)
	}
	switch opts.Filter {
	case "":
		opts.Filter = FilterActive
	case FilterActive, FilterArchived, FilterAll:
	default:
		return fmt.Errorf("%w: unknown archive filter %q", ErrInvalidOptions, opts.Filter)
	}
	if opts.MaxRecords == 0 {
		opts.MaxRecords = MaxExportRecords
	}
	if opts.MaxRecords < 0 || opts.MaxRecords > HardMaxExportRecords {
		return fmt.Errorf("%w: max records must be between 1 and %d", ErrInvalidOptions, HardMaxExportRecords)
	}

	var items []bookmark.Bookmark
	filters := []bool{false}
	switch opts.Filter {
	case FilterArchived:
		filters = []bool{true}
	case FilterAll:
		filters = []bool{false, true}
	}
	for _, archived := range filters {
		// Read one extra row so "exactly MaxRecords" succeeds while
		// "more than MaxRecords" fails deterministically.
		part, err := collect(ctx, svc, ownerID, archived, opts.MaxRecords-len(items)+1)
		if err != nil {
			return err
		}
		items = append(items, part...)
		if len(items) > opts.MaxRecords {
			return fmt.Errorf("%w: more than %d bookmarks", ErrLimitExceeded, opts.MaxRecords)
		}
	}
	sort.Slice(items, func(i, j int) bool {
		pi, pj := folderPath(items[i]), folderPath(items[j])
		if cmp := strings.Compare(strings.Join(pi, "\x00"), strings.Join(pj, "\x00")); cmp != 0 {
			return cmp < 0
		}
		if !items[i].DateAdded.Equal(items[j].DateAdded) {
			return items[i].DateAdded.After(items[j].DateAdded)
		}
		return items[i].ID > items[j].ID
	})

	e := &emitter{w: bufio.NewWriter(w)}
	if err := e.line(0, "<!DOCTYPE NETSCAPE-Bookmark-file-1>"); err != nil {
		return err
	}
	if err := e.line(0, "<!-- Generated by Lynk; contains no credentials. -->"); err != nil {
		return err
	}
	if err := e.line(0, `<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">`); err != nil {
		return err
	}
	if err := e.line(0, "<TITLE>Bookmarks</TITLE>"); err != nil {
		return err
	}
	if err := e.line(0, "<H1>Bookmarks</H1>"); err != nil {
		return err
	}
	if err := e.line(0, "<DL><p>"); err != nil {
		return err
	}

	depth, current := 1, []string{}
	for _, item := range items {
		path := folderPath(item)
		common := commonPrefix(current, path)
		for len(current) > common {
			depth--
			if err := e.line(depth, "</DL><p>"); err != nil {
				return err
			}
			current = current[:len(current)-1]
		}
		for _, name := range path[common:] {
			if err := e.line(depth, "<DT><H3>"+html.EscapeString(name)+"</H3>"); err != nil {
				return err
			}
			if err := e.line(depth, "<DL><p>"); err != nil {
				return err
			}
			depth++
			current = append(current, name)
		}
		if err := e.anchor(depth, item); err != nil {
			return err
		}
	}
	for len(current) > 0 {
		depth--
		if err := e.line(depth, "</DL><p>"); err != nil {
			return err
		}
		current = current[:len(current)-1]
	}
	if err := e.line(0, "</DL><p>"); err != nil {
		return err
	}
	if err := e.w.Flush(); err != nil {
		return fmt.Errorf("flush export: %w", err)
	}
	if opts.Written != nil {
		*opts.Written = len(items)
	}
	return nil
}

func collect(ctx context.Context, svc *bookmark.Service, ownerID int64, archived bool, remaining int) ([]bookmark.Bookmark, error) {
	items := []bookmark.Bookmark{}
	if remaining <= 0 {
		return items, nil
	}
	const pageSize = 200
	for offset := 0; len(items) < remaining; {
		limit := pageSize
		if need := remaining - len(items); need < limit {
			limit = need
		}
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		page, err := svc.List(ctx, ownerID, archived, bookmark.PageOptions{Limit: limit, Offset: offset})
		if err != nil {
			return nil, fmt.Errorf("list bookmarks: %w", err)
		}
		if len(page.Items) == 0 {
			break
		}
		need := remaining - len(items)
		if len(page.Items) > need {
			page.Items = page.Items[:need]
		}
		items = append(items, page.Items...)
		if offset+len(page.Items) >= page.Count {
			break
		}
		offset += len(page.Items)
	}
	return items, nil
}

// folderPath returns the folder components encoded in the first "folder:" tag.
// Tags are stored in name order by the service, so this choice is deterministic.
func folderPath(b bookmark.Bookmark) []string {
	for _, tag := range b.Tags {
		if !strings.HasPrefix(tag, folderPrefix) {
			continue
		}
		parts := strings.Split(strings.TrimPrefix(tag, folderPrefix), "/")
		path := make([]string, 0, len(parts))
		for _, part := range parts {
			part = strings.TrimSpace(part)
			if part != "" {
				path = append(path, part)
			}
			if len(path) >= MaxFolderDepth {
				break
			}
		}
		return path
	}
	return nil
}

func commonPrefix(a, b []string) int {
	for i := range a {
		if i >= len(b) || a[i] != b[i] {
			return i
		}
	}
	return len(a)
}

type emitter struct {
	w *bufio.Writer
}

func (e *emitter) line(depth int, text string) error {
	_, err := fmt.Fprintf(e.w, "%s%s\n", strings.Repeat("    ", depth), text)
	return err
}

func (e *emitter) anchor(depth int, b bookmark.Bookmark) error {
	tags := make([]string, 0, len(b.Tags)+2)
	for _, tag := range b.Tags {
		if strings.HasPrefix(tag, folderPrefix) || tag == TagArchived || tag == TagUnread {
			continue
		}
		tags = append(tags, tag)
	}
	if b.IsArchived {
		tags = append(tags, TagArchived)
	}
	if b.Unread {
		tags = append(tags, TagUnread)
	}
	sort.Strings(tags)

	var attrs strings.Builder
	attrs.WriteString(`<DT><A HREF="`)
	attrs.WriteString(html.EscapeString(b.URL))
	attrs.WriteString(`" ADD_DATE="`)
	attrs.WriteString(strconv.FormatInt(b.DateAdded.Unix(), 10))
	attrs.WriteString(`" LAST_MODIFIED="`)
	attrs.WriteString(strconv.FormatInt(b.DateModified.Unix(), 10))
	attrs.WriteString(`" TAGS="`)
	attrs.WriteString(html.EscapeString(strings.Join(tags, ",")))
	attrs.WriteString(`">`)
	attrs.WriteString(html.EscapeString(b.Title))
	attrs.WriteString(`</A>`)
	if err := e.line(depth, attrs.String()); err != nil {
		return err
	}
	if strings.TrimSpace(b.Description) == "" {
		return nil
	}
	return e.line(depth, "<DD>"+html.EscapeString(b.Description))
}
